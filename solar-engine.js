/**
 * Aplica las variables CSS al :root según la fase solar actual
 */
function applySolarTheme() {
  const phase = getSolarPhase();
  const theme = PHASE_THEMES[phase];
  const root = document.documentElement;

  Object.entries(theme).forEach(([prop, val]) => {
    root.style.setProperty(prop, val);
  });

  root.setAttribute('data-phase', phase);
  document.body.dataset.phase = phase;

  // Actualizar pill de temporada
  const pillIcon = document.querySelector('.phase-pill__icon');
  const pillLabel = document.querySelector('.phase-pill__label');
  if (pillIcon) pillIcon.textContent = theme['--pill-icon'].replace(/"/g, '');
  if (pillLabel) pillLabel.textContent = theme['--pill-label'].replace(/"/g, '');

  return phase;
}

/**
 * Actualiza la UI del header con los datos solares del día
 */
function updateSolarUI() {
  const { sunriseStr, sunsetStr } = getTodaySolarData();
  const phase = applySolarTheme();

  const sunriseEl = document.getElementById('solar-sunrise');
  const sunsetEl  = document.getElementById('solar-sunset');
  const phaseEl   = document.getElementById('solar-phase-text');

  if (sunriseEl) sunriseEl.textContent = sunriseStr;
  if (sunsetEl)  sunsetEl.textContent  = sunsetStr;
  if (phaseEl)   phaseEl.textContent   = phase.charAt(0).toUpperCase() + phase.slice(1);
}

/**
 * Inicializa el motor solar y lo actualiza cada minuto
 */
function initSolarEngine() {
  updateSolarUI();
  // Re-evaluar cada minuto
  setInterval(updateSolarUI, 60_000);
}

