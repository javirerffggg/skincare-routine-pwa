/**
 * Convierte 'HH:MM' a minutos desde medianoche
 */
function timeToMinutes(timeStr) {
  const [h, m] = timeStr.split(':').map(Number);
  return h * 60 + m;
}

/**
 * Obtiene los datos solares del día actual
 * @returns {{ sunrise: number, sunset: number, key: string }}
 */
function getTodaySolarData() {
  const now = new Date();
  const mm = String(now.getMonth() + 1).padStart(2, '0');
  const dd = String(now.getDate()).padStart(2, '0');
  const key = `${mm}-${dd}`;
  const entry = SOLAR_CALENDAR[key] || SOLAR_CALENDAR['06-21']; // fallback
  return {
    key,
    sunrise: timeToMinutes(entry[0]),
    sunset: timeToMinutes(entry[1]),
    sunriseStr: entry[0],
    sunsetStr: entry[1]
  };
}

/**
 * Fases del día:
 * - 'night'    : antes del amanecer o después del ocaso
 * - 'dawn'     : 30 min antes del amanecer
 * - 'day'      : pleno día
 * - 'golden'   : 45 min antes del ocaso
 */
function getSolarPhase() {
  const now = new Date();
  const currentMinutes = now.getHours() * 60 + now.getMinutes();
  const { sunrise, sunset } = getTodaySolarData();

  const dawnStart  = sunrise - 30;
  const goldenStart = sunset - 45;

  if (currentMinutes < dawnStart || currentMinutes >= sunset) {
    return 'night';
  } else if (currentMinutes < sunrise) {
    return 'dawn';
  } else if (currentMinutes >= goldenStart) {
    return 'golden';
  } else {
    return 'day';
  }
}

